-- Scratch Kitchen Staff app: database setup for Supabase.
-- Run once in the Supabase SQL editor. Safe to run again: it skips anything that already exists.
-- Every table is readable and writable only by signed-in staff.

-- ---------- Tables ----------
create table if not exists public.inventory (
  id bigint generated by default as identity primary key,
  name text not null,
  cat text not null default 'Baking' check (cat in ('Baking', 'Catering')),
  unit text not null default 'each',
  on_hand integer not null default 0 check (on_hand >= 0),
  par integer not null default 0,
  cost numeric(10, 2),
  prod text not null default 'Not assigned' check (prod in ('Not assigned', 'Main Production', 'Second Shift Production', 'Both')),
  created_at timestamptz not null default now()
);

create table if not exists public.customers (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null default 'Catering' check (type in ('Catering', 'Bakery')),
  email text not null default '',
  phone text not null default '',
  address text not null default '',
  notes text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.orders (
  id bigint generated by default as identity (start with 1001) primary key,
  customer text not null,
  type text not null default 'Catering' check (type in ('Catering', 'Bakery')),
  due_date date,
  due_time text not null default '',
  -- [{ "invId": 1, "qty": 2 }, ...]
  lines jsonb not null default '[]'::jsonb,
  notes text not null default '',
  -- 0 New, 1 In prep, 2 Ready, 3 Picked up, 4 Skipped
  status smallint not null default 0 check (status between 0 and 4),
  repeat text not null default 'Does not repeat' check (repeat in ('Does not repeat', 'Every day', 'Every week', 'Every 2 weeks', 'Every month')),
  series_id bigint,
  edited boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.needs (
  id bigint generated by default as identity primary key,
  item text not null,
  qty text not null default '1',
  dept text not null default 'Baking' check (dept in ('Baking', 'Catering')),
  done boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  author text not null,
  author_id uuid default auth.uid(),
  text text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  seq integer not null default 1,
  type text not null check (type in ('Order Summary', 'Preparation Sheet V2', '7 Day Order Summary', 'Picking List')),
  area text not null default 'All production' check (area in ('All production', 'Main Production', 'Second Shift Production')),
  name text not null,
  last_run timestamptz,
  created_at timestamptz not null default now()
);

-- One order per day in a repeating series, even if two phones add the next day at once.
create unique index if not exists orders_series_day on public.orders (series_id, due_date) where series_id is not null;

-- ---------- Signed-in staff only ----------
do $$
declare t text;
begin
  foreach t in array array['inventory', 'customers', 'orders', 'needs', 'messages', 'reports'] loop
    execute format('alter table public.%I enable row level security', t);
    if not exists (select 1 from pg_policies where schemaname = 'public' and tablename = t and policyname = 'Staff can do everything') then
      execute format('create policy "Staff can do everything" on public.%I for all to authenticated using (true) with check (true)', t);
    end if;
  end loop;
end $$;

-- Change a stock count by +1 / -1 without two phones overwriting each other.
create or replace function public.adjust_on_hand(p_id bigint, p_delta integer)
returns void
language sql
security invoker
set search_path = ''
as $$
  update public.inventory set on_hand = greatest(0, on_hand + p_delta) where id = p_id;
$$;
revoke execute on function public.adjust_on_hand(bigint, integer) from public, anon;
grant execute on function public.adjust_on_hand(bigint, integer) to authenticated;

-- ---------- Live updates on every phone ----------
do $$
declare t text;
begin
  foreach t in array array['inventory', 'customers', 'orders', 'needs', 'messages', 'reports'] loop
    if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = t) then
      execute format('alter publication supabase_realtime add table public.%I', t);
    end if;
  end loop;
end $$;

